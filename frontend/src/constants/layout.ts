/**
 * 版式常量与断点口径。
 *
 * 全站按三档适配，口径统一在这里，不各页自己拍脑袋：
 *
 *   宽屏 (lg 及以上, ≥992px)   侧栏常驻，表格列开满，筛选器一行排开
 *   窄屏 (md, 768–991px)       侧栏收成抽屉，次要列按容器宽度依次让位
 *   手机 (xs/sm, <768px)       单列堆叠，工具栏整行按钮，表格自己横向滚动
 *
 * 断点值取 Ant Design 的默认栅格断点，与 `Grid.useBreakpoint()` 一致，
 * 这样 CSS 里的 @media 与组件里的判断不会在边界上打架。
 */

/** Ant Design 栅格断点，供 CSS 媒体查询对齐使用 */
export const BREAKPOINTS = {
  sm: 576,
  md: 768,
  lg: 992,
  xl: 1200,
  xxl: 1600,
} as const;

/**
 * 数据表的最小可用宽度。窄于它，表格自己横向滚动。
 *
 * 这解决的是一个具体的坏结果：整页设了 `overflow-x: hidden` 兜底
 * （见 global.css），它保证界面不会被一条长 URL 顶歪，但代价是超出的部分
 * 直接消失——对一张表来说，右半边的列在手机上就**永远够不到**了。
 * 每张表自带横向滚动，把"滚"收在表格内部，内容就都还在。
 *
 * 取 720：一张带勾选框、主标识列、状态列和操作列的表再窄就只剩省略号，
 * 滚动比挤成一团有用。手机竖屏 375、横屏 667 都会触发滚动，这正是预期。
 */
export const MIN_TABLE_WIDTH = 720;

/**
 * 列多、信息密的表（出口代理、API 密钥）用这个更宽的下限。
 * 它们光固定列宽就超过 1000，按 720 承诺等于承诺了一个装不下的宽度。
 */
export const MIN_WIDE_TABLE_WIDTH = 1080;

/** 两三列的小表（熔断列表之类）。定太宽会让卡片里凭空多出一条滚动条。 */
export const MIN_COMPACT_TABLE_WIDTH = 480;
